package org.dromara.dms.controller;

import com.baomidou.mybatisplus.core.conditions.query.QueryWrapper;
import lombok.RequiredArgsConstructor;
import org.dromara.dms.domain.DmsDocCreate;
import org.dromara.dms.domain.DmsDocumentLib;
import org.dromara.dms.domain.DmsDocumentRecordLib;
import org.dromara.dms.domain.DmsTmplLib;
import org.dromara.dms.mapper.DmsDocCreateMapper;
import org.dromara.dms.mapper.DmsDocumentLibMapper;
import org.dromara.dms.mapper.DmsDocumentRecordLibMapper;
import org.dromara.dms.mapper.DmsTmplLibMapper;
import org.dromara.dms.util.SimplePdfWriter;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

/**
 * PDF 预览（本地演示：生成占位 PDF）
 */
@RequiredArgsConstructor
@RestController
public class DmsPdfController {

    private final DmsDocumentLibMapper documentLibMapper;
    private final DmsDocumentRecordLibMapper recordLibMapper;
    private final DmsTmplLibMapper tmplLibMapper;
    private final DmsDocCreateMapper docCreateMapper;

    @GetMapping(value = "/dms/pdf/get/{id}", produces = MediaType.APPLICATION_PDF_VALUE)
    public ResponseEntity<byte[]> pdf(@PathVariable Long id) {
        return build(id, null);
    }

    @GetMapping(value = "/dms/print/browser/preview-pdf", produces = MediaType.APPLICATION_PDF_VALUE)
    public ResponseEntity<byte[]> browserPreview(@RequestParam Long id,
                                                 @RequestParam(required = false) String userId,
                                                 @RequestParam(required = false) String nickName,
                                                 @RequestParam(required = false) String singleOrDouble) {
        return build(id, nickName);
    }

    @GetMapping(value = "/dms/print/pageoffice/preview-pdf", produces = MediaType.APPLICATION_PDF_VALUE)
    public ResponseEntity<byte[]> pageofficePreview(@RequestParam Long id,
                                                    @RequestParam(required = false) String userId,
                                                    @RequestParam(required = false) String nickName,
                                                    @RequestParam(required = false) String singleOrDouble) {
        return build(id, nickName);
    }

    private ResponseEntity<byte[]> build(Long id, String viewer) {
        String title = "DMS Preview";
        List<String> lines = List.of("Document id: " + id,
            "Note: placeholder PDF generated by local demo backend.");
        DmsDocumentLib lib = documentLibMapper.selectById(id);
        if (lib != null) {
            title = "DMS Document";
            lines = List.of("Code: " + nullSafe(lib.getDlCode()), "Name: " + asciiSafe(lib.getDlName()),
                "Version: " + nullSafe(lib.getDlVersion()), "State: " + nullSafe(lib.getUseState()));
        } else {
            DmsDocumentRecordLib record = recordLibMapper.selectById(id);
            if (record != null) {
                title = "DMS Record";
                lines = List.of("Code: " + nullSafe(record.getDlrCode()), "Name: " + asciiSafe(record.getDlrName()),
                    "Version: " + nullSafe(record.getDlrVersion()), "State: " + nullSafe(record.getActiveStatus()));
            } else {
                DmsTmplLib tmpl = tmplLibMapper.selectById(id);
                if (tmpl != null) {
                    title = "DMS Template";
                    lines = List.of("Code: " + nullSafe(tmpl.getTmplCode()), "Name: " + asciiSafe(tmpl.getTmplName()),
                        "Version: " + nullSafe(tmpl.getTmplVersion()));
                } else {
                    DmsDocCreate doc = docCreateMapper.selectById(id);
                    if (doc != null) {
                        title = "DMS Authoring";
                        lines = List.of("Code: " + nullSafe(doc.getDocumentCode()), "Name: " + asciiSafe(doc.getDocumentName()),
                            "Version: " + nullSafe(doc.getDocumentVersion()), "Status: " + nullSafe(doc.getStatus()));
                    }
                }
            }
        }
        if (viewer != null && !viewer.isBlank()) {
            lines = List.copyOf(lines);
        }
        byte[] bytes = SimplePdfWriter.write(title, lines);
        return ResponseEntity.ok()
            .header("Content-Disposition", "inline; filename=preview.pdf")
            .contentType(MediaType.APPLICATION_PDF)
            .body(bytes);
    }

    private String nullSafe(String value) {
        return value == null ? "-" : value;
    }

    private String asciiSafe(String value) {
        return nullSafe(value);
    }
}
